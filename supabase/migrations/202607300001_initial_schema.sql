create or replace function public.get_head_coach_commission(p_coach_id bigint, p_branch_id bigint)
returns jsonb
language plpgsql
security definer
stable
set search_path = public
as $$
declare
  v_students integer;
  v_result jsonb;
begin
  if not public.can_access_branch(p_branch_id) then raise exception 'Branch access denied'; end if;
  if not exists(select 1 from public.coaches where id = p_coach_id and branch_id = p_branch_id and coach_type = 'Head') then raise exception 'Head coach not found'; end if;
  select count(distinct student_id) into v_students
  from public.payments
  where branch_id = p_branch_id and coach_id = p_coach_id and status = 'Paid' and not commission_settled;
  with units as (
    select p.id, p.student_id, s.name as student_name, p.fee_month, p.date_received, s.monthly_fee,
      coalesce((select r.payout from public.head_coach_rates r
        where v_students between r.min_students and r.max_students
          and s.monthly_fee between r.min_fee and r.max_fee
        order by r.min_students desc, r.min_fee desc limit 1), 0) as payout
    from public.payments p
    join public.students s on s.id = p.student_id
    where p.branch_id = p_branch_id and p.coach_id = p_coach_id and p.status = 'Paid' and not p.commission_settled
  )
  select jsonb_build_object(
    'type', 'Head',
    'units', count(*),
    'students', v_students,
    'commission', coalesce(sum(payout), 0),
    'unmatched', count(*) filter (where monthly_fee is null or payout = 0),
    'items', coalesce(jsonb_agg(jsonb_build_object(
      'paymentId', id,
      'studentId', student_id,
      'studentName', student_name,
      'feeMonth', to_char(fee_month, 'YYYY-MM'),
      'dateReceived', date_received,
      'receivedMonth', to_char(date_received, 'YYYY-MM'),
      'fee', monthly_fee,
      'payout', payout
    ) order by date_received desc nulls last, student_name, fee_month), '[]'::jsonb)
  ) into v_result from units;
  return v_result;
end;
$$;

create or replace function public.get_assistant_pay(p_coach_id bigint, p_branch_id bigint, p_month date)
returns jsonb
language plpgsql
security definer
stable
set search_path = public
as $$
declare
  v_rate numeric;
  v_result jsonb;
begin
  if not public.can_access_branch(p_branch_id) then raise exception 'Branch access denied'; end if;
  select hourly_rate into strict v_rate from public.coaches
  where id = p_coach_id and branch_id = p_branch_id and coach_type = 'Assistant';
  with entries as (
    select ca.attendance_date, c.label as class_name, ca.hours
    from public.coach_attendance ca
    join public.classes c on c.id = ca.class_id
    where ca.coach_id = p_coach_id and ca.branch_id = p_branch_id
      and ca.attendance_date >= date_trunc('month', p_month)::date
      and ca.attendance_date < (date_trunc('month', p_month) + interval '1 month')::date
  )
  select jsonb_build_object(
    'type', 'Assistant',
    'month', to_char(p_month, 'YYYY-MM'),
    'hours', coalesce(sum(hours), 0),
    'hourlyRate', v_rate,
    'total', coalesce(sum(hours), 0) * v_rate,
    'sessions', coalesce(jsonb_agg(jsonb_build_object('date', attendance_date, 'className', class_name, 'hours', hours) order by attendance_date desc), '[]'::jsonb)
  ) into v_result from entries;
  return v_result;
end;
$$;

create or replace function public.record_coach_payout(
  p_coach_id bigint,
  p_amount numeric,
  p_units numeric,
  p_rate numeric,
  p_students_count integer,
  p_date_paid date,
  p_remarks text default '',
  p_pay_month date default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_coach public.coaches%rowtype;
  v_payout_id bigint;
  v_payment_ids bigint[] := '{}'::bigint[];
  v_students_count integer := p_students_count;
  v_units numeric := p_units;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  select * into strict v_coach from public.coaches where id = p_coach_id for update;
  if not public.can_access_branch(v_coach.branch_id) then raise exception 'Branch access denied'; end if;
  if v_coach.coach_type = 'Head' then
    select coalesce(array_agg(id), '{}'::bigint[]), count(distinct student_id)
    into v_payment_ids, v_students_count
    from (
      select p.id, p.student_id
      from public.payments p
      where p.branch_id = v_coach.branch_id and p.coach_id = v_coach.id and p.status = 'Paid' and not p.commission_settled
      for update
    ) locked_payments;
    v_units = cardinality(v_payment_ids);
  end if;
  insert into public.coach_payments (branch_id, coach_id, payout_type, pay_month, amount, units, rate, students_count, date_paid, remarks)
  values (v_coach.branch_id, v_coach.id, v_coach.coach_type::text::public.payout_type, p_pay_month, p_amount, v_units, p_rate, v_students_count, p_date_paid, coalesce(p_remarks, ''))
  returning id into v_payout_id;
  if v_coach.coach_type = 'Head' then
    with lines as (
      select p.id, p.student_id, s.monthly_fee,
        coalesce((select r.payout from public.head_coach_rates r
          where v_students_count between r.min_students and r.max_students
            and s.monthly_fee between r.min_fee and r.max_fee
          order by r.min_students desc, r.min_fee desc limit 1), 0) as line_payout
      from public.payments p
      join public.students s on s.id = p.student_id
      where p.id = any(v_payment_ids)
    )
    insert into public.coach_payment_lines (coach_payment_id, payment_id, student_id, student_fee, students_count, payout, matched)
    select v_payout_id, id, student_id, monthly_fee, v_students_count, line_payout, monthly_fee is not null and line_payout > 0
    from lines;
    update public.payments p
    set commission_settled = true, coach_payment_id = v_payout_id, updated_at = now()
    where p.id = any(v_payment_ids);
  end if;
  return v_payout_id;
end;
$$;

create or replace function public.undo_coach_payout(p_coach_payment_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_branch bigint;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  select branch_id into strict v_branch from public.coach_payments where id = p_coach_payment_id for update;
  if not public.can_access_branch(v_branch) then raise exception 'Branch access denied'; end if;
  update public.payments set commission_settled = false, coach_payment_id = null, updated_at = now()
  where coach_payment_id = p_coach_payment_id;
  delete from public.coach_payments where id = p_coach_payment_id;
end;
$$;

