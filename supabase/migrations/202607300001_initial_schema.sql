create or replace function public.protect_last_active_branch()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'DELETE' then
    if old.status = 'Active' and not exists(select 1 from public.branches where id <> old.id and status = 'Active') then
      raise exception 'Cannot deactivate or delete the only active branch';
    end if;
    return old;
  end if;
  if old.status = 'Active' and new.status = 'Inactive'
    and not exists(select 1 from public.branches where id <> old.id and status = 'Active') then
    raise exception 'Cannot deactivate or delete the only active branch';
  end if;
  return new;
end;
$$;

create trigger branches_protect_last before update or delete on public.branches for each row execute function public.protect_last_active_branch();

