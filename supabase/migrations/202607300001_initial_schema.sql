create or replace function public.generate_sessions(p_class_id bigint, p_start_date date, p_end_date date)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_class public.classes%rowtype;
  v_date date;
  v_created integer := 0;
  v_target integer;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  if p_end_date < p_start_date then raise exception 'End date must be after start date'; end if;
  select * into strict v_class from public.classes where id = p_class_id;
  if not public.can_access_branch(v_class.branch_id) then raise exception 'Branch access denied'; end if;
  v_target = array_position(array['Sunday','Monday','Tuesday','Wednesday','Thursday','Friday','Saturday'], v_class.day_of_week) - 1;
  v_date = p_start_date;
  while extract(dow from v_date)::integer <> v_target and v_date <= p_end_date loop
    v_date = v_date + 1;
  end loop;
  while v_date <= p_end_date loop
    insert into public.sessions (branch_id, class_id, session_date, coach_id)
    values (v_class.branch_id, v_class.id, v_date, v_class.coach_id)
    on conflict (class_id, session_date) do nothing;
    if found then v_created = v_created + 1; end if;
    v_date = v_date + 7;
  end loop;
  return v_created;
end;
$$;

create or replace function public.record_student_payment(
  p_student_id bigint,
  p_fee_months date[],
  p_amount numeric,
  p_method public.payment_method,
  p_status public.payment_status,
  p_date_received date,
  p_remarks text default '',
  p_reference_no text default '',
  p_coach_id bigint default null,
  p_receipt_path text default null
)
returns bigint[]
language plpgsql
security definer
set search_path = public
as $$
declare
  v_branch bigint;
  v_primary date;
  v_month date;
  v_id bigint;
  v_ids bigint[] := '{}';
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  if coalesce(array_length(p_fee_months, 1), 0) = 0 then raise exception 'At least one fee month is required'; end if;
  select branch_id into strict v_branch from public.students where id = p_student_id;
  if not public.can_access_branch(v_branch) then raise exception 'Branch access denied'; end if;
  select max(date_trunc('month', month_value)::date) into v_primary from unnest(p_fee_months) as months(month_value);
  foreach v_month in array p_fee_months loop
    v_month = date_trunc('month', v_month)::date;
    insert into public.payments (
      branch_id, student_id, fee_month, amount, method, status, date_received,
      remarks, reference_no, coach_id, receipt_path
    ) values (
      v_branch,
      p_student_id,
      v_month,
      case when v_month = v_primary then p_amount else 0 end,
      p_method,
      p_status,
      p_date_received,
      case when v_month = v_primary then coalesce(p_remarks, '') else 'Paid in ' || to_char(v_primary, 'FMMonth YYYY') end,
      case when v_month = v_primary then coalesce(p_reference_no, '') else '' end,
      p_coach_id,
      p_receipt_path
    ) returning id into v_id;
    v_ids = array_append(v_ids, v_id);
  end loop;
  return v_ids;
end;
$$;

create or replace function public.replace_head_coach_rates(p_rates jsonb)
